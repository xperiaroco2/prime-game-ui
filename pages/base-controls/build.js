class BuildError extends Error {}
const fail = (msg) => { throw new BuildError(msg); };
const readText = (r) => fs.readFileSync(path.join(ROOT, r), 'utf8').replace(/\r\n/g, '\n');
const readJson = (r) => JSON.parse(readText(r));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const num = (x) => String(x).replace('.', ',');
const ruleText = (sel, decls) => [`${sel} {`, ...decls.map(([p, v]) => `  ${p}: ${v};`), '}'].join('\n');
const varRefs = (text) => [...text.matchAll(/var\((--toy-[\w-]+)\)/g)].map((m) => m[1]);

// ---------------------------------------------------------------------------------------------------------------
// StyleBoxFlat rules from token names (the emitter's forms: lengths are calc(var(--toy-…) * var(--px)), a content
// margin is drawn as padding inside the border).
const T = (n) => `var(--toy-${n})`;
const len = (n) => `calc(${T(n)} * var(--px))`;
const pad = (margin, border) => (border ? `calc((${T(margin)} - ${T(border)}) * var(--px))` : len(margin));
function box({ bg, line, width, radius, block, inline, left }) {
  const d = [['box-sizing', 'border-box'], ['position', 'relative'], ['background', T(bg)]];
  if (!line) d.push(['border-style', 'none']);
  if (line) {
    d.push(['border-style', 'solid'], ['border-color', T(line)]);
    for (const s of ['top', 'right', 'bottom', 'left']) d.push([`border-${s}-width`, len(width)]);
  }
  for (const c of ['top-left', 'top-right', 'bottom-right', 'bottom-left']) d.push([`border-${c}-radius`, len(radius)]);
  const b = line ? width : null;
  d.push(['padding-top', pad(block, b)], ['padding-right', pad(inline, b)], ['padding-bottom', pad(block, b)], ['padding-left', pad(left || inline, b)]);
  return d;
}
const font = (type, color) => [
  ['font-family', `${T(`type-${type}-font-family`)}, system-ui, sans-serif`],
  ['font-size', len(`type-${type}-font-size`)],
  ['font-weight', T(`type-${type}-font-weight`)],
  ['line-height', T(`type-${type}-line-height`)],
  ['color', T(color)],
];

// The new looks, per option. Each is a list of [selector, decls].
function looks() {
  const R = [];
  const rule = (sel, decls) => R.push({ sel, decls });
  // q1: the CheckBox. a and b: a white plate (the setting row's white, a thin ink outline, medium corners) holding the
  // 28 px box texture and the label, 12 px apart (h_separation); c: no plate.
  const plate = { bg: 'palette-white', line: 'color-outline', width: 'stroke-thin', radius: 'radius-medium', block: 'space-8', inline: 'space-16', left: 'space-12' };
  for (const k of ['a', 'b']) {
    const c = `.tv-BcCheck${k.toUpperCase()}`;
    rule(c, [...box(plate), ...font('body', 'color-on-light-text'), ['column-gap', len('space-12')], ['cursor', 'pointer']]);
    rule(`${c}.is-hover`, [['background', T('color-state-hover-on-light')]]);
    rule(`${c}.is-disabled`, [['background', T('color-state-disabled-face')], ['border-color', T('color-state-disabled-ink')], ['color', T('color-state-disabled-ink')]]);
  }
  // b: checked (Godot's pressed and hover_pressed styleboxes) paints the plate yellow; disabled and checked: lavender.
  rule('.tv-BcCheckBOn', [...box(Object.assign({}, plate, { bg: 'palette-yellow' })), ...font('body', 'color-on-accent-text'), ['column-gap', len('space-12')], ['cursor', 'pointer']]);
  rule('.tv-BcCheckBOn.is-disabled', [['background', T('palette-lavender')], ['border-color', T('color-state-disabled-ink')], ['color', T('color-state-disabled-ink')]]);
  rule('.tv-BcCheckC', [...box({ bg: 'palette-clear', radius: 'radius-small', block: 'space-4', inline: 'space-8' }), ...font('body', 'color-on-light-text'), ['column-gap', len('space-12')], ['cursor', 'pointer']]);
  rule('.tv-BcCheckC.is-hover', [['background', T('color-state-hover-on-light')]]);
  rule('.tv-BcCheckC.is-disabled', [['color', T('color-state-disabled-ink')]]);

  // q2 a: two stacked buttons beside the field in the setting stepper's colours, small corners.
  const st = (n) => `setting-stepper-${n}`;
  rule('.tv-BcSpinA', [...box({ bg: st('normal-bg-color'), line: st('normal-border-color'), width: st('normal-border-width'), radius: 'radius-small', block: 'space-4', inline: 'space-8' }), ['cursor', 'pointer']]);
  rule('.tv-BcSpinA.is-held', [['background', T(st('pressed-bg-color'))]]);
  rule('.tv-BcSpinA.is-disabled', [['background', T(st('disabled-bg-color'))], ['border-color', T(st('disabled-border-color'))]]);
  rule('.tv-BcSpinA .tv-icon', [['color', T(st('items-icon-normal-color'))]]);
  rule('.tv-BcSpinA.is-hover .tv-icon', [['color', T(st('items-icon-hover-color'))]]);
  rule('.tv-BcSpinA.is-held .tv-icon', [['color', T(st('items-icon-pressed-color'))]]);
  rule('.tv-BcSpinA.is-disabled .tv-icon', [['color', T(st('items-icon-disabled-color'))]]);
  // q2 b: the arrows inside the field, behind a thin ink separator; a half lights up lavender on hover, yellow held.
  rule('.tv-BcSpinB', [...box({ bg: 'palette-clear', radius: 'radius-small', block: 'space-4', inline: 'space-4' }), ['cursor', 'pointer']]);
  rule('.tv-BcSpinB.is-hover', [['background', T('color-state-hover-on-light')]]);
  rule('.tv-BcSpinB.is-held', [['background', T('palette-yellow')]]);
  rule('.tv-BcSpinB .tv-icon', [['color', T('field-input-normal-font-color')]]);
  rule('.tv-BcSpinB.is-disabled .tv-icon', [['color', T('color-state-disabled-ink')]]);
  rule('.tv-BcSpinSep', [['background', T('color-outline')], ['width', len('stroke-thin')], ['align-self', 'stretch']]);
  return R;
}

