const fs = require('fs');
const path = require('path');

const HERE = __dirname;
const ROOT = path.resolve(HERE, '..', '..');
const api = require(path.join(ROOT, 'tools', 'tokens', 'api.js'));
const { emitComponentsCss } = require(path.join(ROOT, 'pages', 'components', 'emit-css.js'));
const { tokenVars, splitBlocks } = require(path.join(ROOT, 'pages', 'choices', 'build.js'));

const OUT_TOKENS = 'pages/base-controls/base-controls-tokens.css';
