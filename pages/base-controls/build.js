// The base-controls review page (prime-game-ui#52, for prime-game#620): looks for a bare CheckBox, the SpinBox's arrows
// and a plain Button, and the large-text default_font_size, each as 2 or 3 options with one recommendation.
//
//   node pages/base-controls/build.js          write base-controls-tokens.css, base-controls.css, base-controls.html
//   node pages/base-controls/build.js --check  fail when any of them is stale
//
// Nothing here changes tokens/: an option that reuses a variation (the plain Button) draws with the showcase's emitted
// CSS of that variation (pages/components/emit-css.js); a new look (the CheckBox's plate, the SpinBox's arrow buttons)
// is drawn as StyleBoxFlat rules written from token variables only, so the Godot-safe lint ("generated" profile) reads
// it like any emitted variation. The CheckBox's box and the arrows are textures in Godot (icons), drawn here as inline
// SVG in palette colours. Large text: every rule whose token resolves differently in the large text size is repeated
// under .bc-large with the large value, read from --toy-bc-large-<name> in base-controls-tokens.css ("tokens" profile;
// generated CSS may not declare --toy-* variables). The answers are saved by pages/choices/choices.js (collection
// "base-controls", one document per question: { answer, text, note, at }).
// Node 20, no packages.
