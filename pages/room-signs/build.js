function loadSystems() {
  const out = {};
  for (const sid of SIDS) {
    const dir = `pages/room-signs/systems/${sid}`;
    let json, lic;
    try { json = JSON.parse(readText(`${dir}/system.json`)); } catch (e) { fail(`${dir}/system.json: ${e.message}`); }
    try { lic = JSON.parse(readText(`${dir}/LICENCES.json`)); } catch (e) { fail(`${dir}/LICENCES.json: ${e.message}`); }
    const ids = (json.rooms || []).map((r) => r.id);
    if (ids.join() !== ROOMS.join()) fail(`${dir}/system.json: rooms ${ids.join(', ')}; expected ${ROOMS.join(', ')}`);
    const rooms = {};
    for (const r of json.rooms) {
      const takes = 'takes_deliveries' in r ? r.takes_deliveries : r.deliveries;
      if (typeof takes !== 'boolean') fail(`${dir}/system.json: room ${r.id} does not say whether it takes deliveries`);
      rooms[r.id] = { name: r.name_uk, takes, optional: !!r.optional, raw: r };
    }
    out[sid] = { id: sid, dir, json, lic, rooms, name: json.name_uk, pitch: json.pitch_uk };
  }
  for (const r of ROOMS) {
    const v = SIDS.map((s) => `${out[s].rooms[r].name}|${out[s].rooms[r].takes}|${out[s].rooms[r].optional}`);
    if (new Set(v).size !== 1) fail(`room ${r}: the systems disagree on its name, deliveries or being optional (${v.join(' / ')})`);
  }
  return out;
}

// ---------- SVG files as symbols ----------

const SVG_COLOURS = { '#2a1f33': 'var(--rs-ink)', '#fff4e2': 'var(--rs-cream)' };

function svgSource(sys, rel) {
  const entry = sys.lic[rel];
  if (!entry || !/^own work$/i.test(String(entry.licence))) fail(`${sys.dir}/${rel}: not recorded as own work in LICENCES.json`);
  const text = readText(`${sys.dir}/${rel}`);
  if (/<(script|image|foreignObject|text|style|a|use|filter|mask|linearGradient|radialGradient|pattern)\b|href=|\son[a-z]+=|url\(/i.test(text)) {
    fail(`${sys.dir}/${rel}: only plain shapes are inlined (no text, links, filters, masks, gradients or scripts)`);
  }
  return text;
}

// One symbol per file: the hex fills and strokes become var(--rs-ink) / var(--rs-cream) in a style attribute, so a
// colour-vision wrapper repaints every <use> of it through inheritance.
function symbolOf(id, text, where) {
  const m = /^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(text);
  if (!m) fail(`${where}: not one <svg> element`);
  const vb = /\bviewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(m[1]);
  if (!vb) fail(`${where}: no viewBox "0 0 w h"`);
  const body = m[2].replace(/<([a-zA-Z]+)\b([^>]*?)(\/?)>/g, (all, tag, attrs, self) => {
    const style = [];
    const rest = attrs.replace(/\s(fill|stroke)="(#[0-9a-fA-F]{6})"/g, (a, prop, hex) => {
      const v = SVG_COLOURS[hex.toLowerCase()];
      if (!v) fail(`${where}: colour ${hex} is not the tokens' ink or cream`);
      style.push(`${prop}:${v}`);
      return '';
    });
    if (style.length && /\sstyle=/.test(rest)) fail(`${where}: a style attribute next to a colour`);
    return `<${tag}${rest}${style.length ? ` style="${style.join(';')}"` : ''}${self}>`;
  }).replace(/>\s+</g, '><').trim();
  if (/#[0-9a-fA-F]{3,8}\b/.test(body)) fail(`${where}: a colour outside fill and stroke`);
  return { id, w: Number(vb[1]), h: Number(vb[2]), body };
}

