function loadCvd() {
  // tools/a11y/cvd.js is a script, not a module: run it unchanged with its printing silenced and take its functions.
  const src = readText('tools/a11y/cvd.js');
  const out = vm.runInNewContext(`${src}\n;({ simulateLin, toLin, toSrgb, linToLab, de2000 });`, { console: { log() {} } }, { filename: 'tools/a11y/cvd.js', timeout: 60000 });
  for (const k of ['simulateLin', 'toLin', 'toSrgb', 'linToLab', 'de2000']) if (typeof out[k] !== 'function') fail(`tools/a11y/cvd.js: no ${k}`);
  return out;
}

function parseColour(v) {
  let m = /^#([0-9a-fA-F]{6})$/.exec(v);
  if (m) return { rgb: wcag.fromHex(v).slice(0, 3), a: null };
  m = /^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)$/.exec(v);
  if (m) return { rgb: [m[1], m[2], m[3]].map((x) => Number(x) / 255), a: Number(m[4]) };
  return null;
}

function rootVars(css, prefix, where) {
  const m = /:root \{\n([\s\S]*?)\n\}/.exec(css);
  if (!m) fail(`${where}: no :root block`);
  const map = new Map();
  for (const l of m[1].split('\n')) {
    const d = /^\s*(--[\w-]+):\s*(.+?);\s*$/.exec(l);
    if (d && d[1].startsWith(prefix)) map.set(d[1], d[2]);
  }
  return map;
}

function resolver(maps) {
  const get = (name, depth) => {
    if (depth > 30) fail(`${name}: alias loop`);
    for (const m of maps) if (m.has(name)) {
      const v = m.get(name);
      const a = /^var\((--[\w-]+)\)$/.exec(v);
      return a ? get(a[1], depth + 1) : v;
    }
    fail(`${name}: not declared`);
    return null;
  };
  return (name) => get(name, 0);
}

function simulate(cvd, rgb, vision) {
  return cvd.simulateLin(rgb.map(cvd.toLin), vision).map(cvd.toSrgb);
}
function colourText(c, rgb) {
  if (c.a === null) return wcag.toHex(rgb);
  return `rgba(${rgb.map((x) => Math.round(Math.min(1, Math.max(0, x)) * 255)).join(', ')}, ${c.a})`;
}

